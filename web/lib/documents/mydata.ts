// Μονάδα μέτρησης myDATA (measurementUnit) από τη διάσταση της μονάδας της εφαρμογής (Unit.dimension):
// 1 τεμάχια, 2 κιλά, 3 λίτρα. Οι ποσότητες της εφαρμογής είναι σε mg / ml / τεμάχια (βασική μονάδα).
export function myDataUnit(dimension: string): { code: 1 | 2 | 3; perBase: number } {
  if (dimension === "mass") return { code: 2, perBase: 1_000_000 }; // mg → kg
  if (dimension === "volume") return { code: 3, perBase: 1_000 }; // ml → l
  if (dimension === "count") return { code: 1, perBase: 1 };
  throw new RangeError(`Άγνωστη διάσταση μονάδας: ${dimension}`);
}
